SPACE_ADVANCE = 4


def glyph_rows(rows):
    rows = list(rows) + ["." * len(rows[0])] * (CELL_H - len(rows))
    return rows[:CELL_H]


def main():
    chars = sorted(G.keys(), key=ord)
    cols = 16
    cell_w = 6
    rows_n = (len(chars) + cols - 1) // cols
    sheet = Image.new("RGBA", (cols * cell_w, rows_n * (CELL_H + 1)), (0, 0, 0, 0))
    lines = []
    for i, ch in enumerate(chars):
        rows = glyph_rows(G[ch])
        width = max(len(r) for r in rows)
        rows = [r.ljust(width, ".") for r in rows]
        used = [x for x in range(width) if any(r[x] == "#" for r in rows)]
        left, right = (used[0], used[-1]) if used else (0, 0)
        w = right - left + 1
        ox, oy = (i % cols) * cell_w, (i // cols) * (CELL_H + 1)
        for y, r in enumerate(rows):
            for x in range(left, right + 1):
                if r[x] == "#":
                    sheet.putpixel((ox + x - left, oy + y), (255, 255, 255, 255))
        lines.append(
            f"char id={ord(ch)} x={ox} y={oy} width={w} height={CELL_H} xoffset=0 yoffset=0 "
            f"xadvance={w + 1} page=0 chnl=15"
        )
    lines.insert(0, f"char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance={SPACE_ADVANCE} page=0 chnl=15")
    os.makedirs(OUT_DIR, exist_ok=True)
    sheet.save(os.path.join(OUT_DIR, NAME + ".png"))
    header = [
        f'info face="Mech Pixel" size={LINE_H} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=1,1 outline=0',
        f"common lineHeight={LINE_H} base={BASE} scaleW={sheet.width} scaleH={sheet.height} pages=1 packed=0",
        f'page id=0 file="{NAME}.png"',
        f"chars count={len(lines)}",
    ]
    with open(os.path.join(OUT_DIR, NAME + ".fnt"), "w") as f:
        f.write("\n".join(header + lines) + "\n")
    print(f"{len(lines)} glyphs")


if __name__ == "__main__":
    main()
